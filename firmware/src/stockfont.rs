/// Hand-drawn 1 bpp glyphs for SC_F12 (the scope bar's 12 px font has ASCII
/// only): Ω and ° for the REC mark's function (scope_ui::rec_unit), drawn on
/// the font's cap rows (2..10) with its 2 px stems; column-major, MSB first.
///   Ω  ...###..  ..##.##.  .##...##  .##...##  .##...##  ..##.##.
///      ...#.#..  ...#.#..  .###.###        °  ..##.  .#..#  .#..#  ..##.
static F12_GLYPHS: [(u32, char, bool, u8, u8, u8, i8, &[u8]); 2] = [
    (0x0804_F24C, '\u{3a9}', false, 8, 9, 8, 1, &[0x00, 0x1c, 0x5f, 0x38, 0xf8, 0x06, 0x3d, 0xf2, 0x71]),
    (0x0804_F24C, '\u{b0}', false, 5, 4, 6, 6, &[0x06, 0x99, 0x60]),
];

/// Glyph of `ch`. The stock DMM fonts have only the units they need: no W in
/// UNIT / LETTERS / SC_DIGITS / HIST (power meter, dmm::pw), no k in LETTERS
/// ("kWh"); those take ours of the same face (stockfont_w.rs), any other font
/// without a W two of its 'V' overlapped, the second `twin` px to the right.
/// Returns (glyph, twin).
fn glyph_or_twin(font: Font, ch: char) -> Option<(Glyph, i16)> {
    if let Some(g) = font.glyph(ch as u32) {
        return Some((g, 0));
    }
    match OWN_GLYPHS.iter().chain(USB_GLYPHS.iter()).chain(F12_GLYPHS.iter()).find(|o| o.0 == font.0 && o.1 == ch) {
        Some(&(_, _, four, w, h, adv, yoff, b)) => Some((Glyph::own(b, four, w, h, adv, yoff), 0)),
        None if ch == 'W' => font.glyph('V' as u32).map(|g| (g, (g.w as i16 * 9 + 8) / 16)),
        None => None,
    }
}

/// Coverage at column `gx` (0 .. w + twin) of a glyph row decoded into
/// `buf` (`Glyph::row`), the synthesised twin included.
#[inline(always)]
fn twin_buf(buf: &[u8; MAXW], w: u8, twin: i16, gx: usize) -> u8 {
    let w = (w as usize).min(MAXW);
    let a = if gx < w { buf[gx] } else { 0 };
    let t = twin as usize;
    if t > 0 && gx >= t && gx - t < w { a.max(buf[gx - t]) } else { a }
}

/// Coverage of a placed glyph at column `gx` (0.. w + twin) and row `gy`.
fn twin_alpha(g: &Glyph, twin: i16, gx: u32, gy: u32) -> u8 {
    let w = g.w as u32;
    let a = if gx < w { g.alpha(gx, gy) } else { 0 };
    let t = twin as u32;
    if t > 0 && gx >= t && gx - t < w { a.max(g.alpha(gx - t, gy)) } else { a }
}

fn layout(font: Font, r: Rect, text: &str, align: u8, spacing: i8, out: &mut [Option<Placed>; MAXG]) -> usize {
    // Measure.
    let mut n = 0;
    let mut tw: i32 = 0;
    let mut last_w = 0i32;
    let mut pen = 0i32;
    let lh = font.line_h() as i32;
    let mut xs = [0i32; MAXG];
    let mut gs: [Option<(Glyph, i16)>; MAXG] = [None; MAXG];
    for ch in text.chars() {
        if n == MAXG {
            break;
        }
        let g = glyph_or_twin(font, ch);
        xs[n] = pen;
        gs[n] = g;
        match g {
            Some((g, tw)) => {
                // A space advances at least a third of the line height: the
                // stock F14 space glyph advances 1 px ("40rows").
                pen += (if ch == ' ' { (g.adv as i32).max(lh / 3) } else { g.adv as i32 + tw as i32 }) + spacing as i32;
                last_w = g.w as i32 + tw as i32;
            }
            None => {
                pen += lh;
                last_w = lh;
            }
        }
        n += 1;
    }
    if n > 0 {
        tw = xs[n - 1] + last_w;
    }
    let th = lh;
    let ox = match align {
        0..=2 => 0,
        3..=5 => r.w as i32 - tw,
        _ => (r.w as i32 - tw) >> 1,
    };
    let oy = match align {
        0 | 3 | 6 => 0,
        2 | 5 | 7 => r.h as i32 - th,
        _ => (r.h as i32 - th) >> 1,
    };
    let desc = font.descent() as i32;
    for i in 0..n {
        out[i] = gs[i].map(|(g, twin)| Placed {
            g,
            x: (r.x as i32 + ox + xs[i]) as i16,
            y: (r.y as i32 + oy + lh - desc - g.h as i32 - g.yoff as i32) as i16,
            twin,
            cur: Cur::default(),
        });
    }
    #[cfg(test)]
    probe_fit(r, text, out[..n].iter().flatten().map(|p| (&p.g, p.twin, p.x, p.y)), 4);
    n
}

/// ui-render's clip rule (cfg(test)): the ink (pixels of coverage >= `thr`
/// of 15) of a text laid out in `r` must lie inside `r` (`label` / `paint`
/// cut what is outside; `glyphs` would draw over its neighbour). The glyph
/// boxes are not enough: a bitmap has blank columns / rows.
#[cfg(test)]
static mut FIT_EXEMPT: bool = false;

/// Stock-replica texts whose stock box cuts them (scope_ui brackets): not
/// reported by `probe_fit` while on.
#[cfg(test)]
pub fn fit_exempt(on: bool) {
    unsafe { FIT_EXEMPT = on };
}

#[cfg(test)]
fn probe_fit<'a>(r: Rect, text: &str, gs: impl Iterator<Item = (&'a Glyph, i16, i16, i16)>, thr: u8) {
    if unsafe { FIT_EXEMPT } {
        return;
    }
    let (rx0, ry0, rx1, ry1) = (r.x as i32, r.y as i32, r.x as i32 + r.w as i32 - 1, r.y as i32 + r.h as i32 - 1);
    let mut b = (i32::MAX, i32::MAX, i32::MIN, i32::MIN);
    for (g, twin, x, y) in gs {
        let (gw, gh) = (g.w as i32 + twin as i32, g.h as i32);
        // Only glyph boxes that cross the box edge can have ink outside.
        if x as i32 >= rx0 && y as i32 >= ry0 && x as i32 + gw - 1 <= rx1 && y as i32 + gh - 1 <= ry1 {
            continue;
        }
        for gy in 0..g.h as u32 {
            for gx in 0..(g.w as i16 + twin).max(0) as u32 {
                if twin_alpha(g, twin, gx, gy) >= thr {
                    let (px, py) = (x as i32 + gx as i32, y as i32 + gy as i32);
                    b = (b.0.min(px), b.1.min(py), b.2.max(px), b.3.max(py));
                }
            }
        }
    }
    if b.0 <= b.2 && (b.0 < rx0 || b.1 < ry0 || b.2 > rx1 || b.3 > ry1) {
        crate::probe::fit((rx0, ry0, rx1, ry1), b, text);
    }
}

/// 16-step colour ramp bg..fg for one label (avoids per-pixel arithmetic).
pub fn ramp(fg: Color, bg: Color) -> [Color; 16] {
    let mut t = [0; 16];
    for (a, v) in t.iter_mut().enumerate() {
        *v = blend(fg, bg, a as u8);
    }
    t
}

fn blend(fg: Color, bg: Color, a: u8) -> Color {
    if a == 0 {
        return bg;
    }
    if a >= 15 {
        return fg;
    }
    let a = a as i32;
    let ch = |c: Color, s: u32, m: u32| ((c as u32 >> s) & m) as i32;
    let mix = |s: u32, m: u32| ((ch(bg, s, m) + (ch(fg, s, m) - ch(bg, s, m)) * a / 15) as u32 & m) << s;
    (mix(11, 0x1F) | mix(5, 0x3F) | mix(0, 0x1F)) as Color
}

/// Draw `text` in `r` (background `bg` fills the whole rect, so a redraw
/// replaces the old text without flicker).
pub fn label(font: Font, r: Rect, text: &str, fg: Color, bg: Color, align: u8, spacing: i8) {
    if r.w <= 0 || r.h <= 0 {
        return;
    }
    // A strip pass (lcd.rs "strip rendering"): only the strip's rows.
    let Some((ya, yb)) = lcd::clip_rows(r.y.max(0), (r.y + r.h - 1).min(lcd::H as i16 - 1)) else {
        return;
    };
    let mut pl: [Option<Placed>; MAXG] = [const { None }; MAXG];
    let n = layout(font, r, text, align, spacing, &mut pl);
    let x1 = (r.x + r.w - 1).min(lcd::W as i16 - 1);
    let (x0, y0, y1) = (r.x.max(0), ya, yb);
    // Per column: the glyph covering it (last one wins on 1-2 px overlaps of
    // negative spacing), so each pixel needs one lookup instead of a scan.
    let mut cover = [u8::MAX; 480];
    for (gi, p) in pl[..n].iter().enumerate() {
        if let Some(p) = p {
            for gx in 0..p.g.w as i16 + p.twin {
                let x = p.x + gx;
                if x >= x0 && x <= x1 {
                    cover[x as usize] = gi as u8;
                }
            }
        }
    }
    let lut = ramp(fg, bg);
    #[cfg(test)]
    crate::probe::begin(crate::probe::TEXT, bg);
    lcd::set_window(x0 as u16, y0 as u16, x1 as u16, y1 as u16);
    // One glyph row at a time (`Glyph::row`): `bi` = the glyph whose row y
    // is in `buf`.
    let mut buf = [0u8; MAXW];
    for y in y0..=y1 {
        // Runs of columns with the same covering glyph: background runs are
        // a plain fill, glyph runs read the glyph's row y.
        let mut bi = u8::MAX;
        let mut x = x0;
        let mut out = lcd::row_out(y, x0);
        while x <= x1 {
            let gi = cover[x as usize];
            let mut e = x + 1;
            while e <= x1 && cover[e as usize] == gi {
                e += 1;
            }
            #[cfg(test)]
            crate::probe::sub(gi);
            let hit = match pl.get_mut(gi as usize) {
                Some(Some(p)) if y >= p.y && y - p.y < p.g.h as i16 => Some(p),
                _ => None,
            };
            match hit {
                // 1 bpp / raw 4 bpp: straight from the bitmap, a column step
                // per pixel (column-major bitmap, row-major window).
                Some(p) if p.twin == 0 && p.g.col_walk(0).is_some() => match p.g.col_walk((y - p.y) as u32).flatten() {
                    Some((i0, st)) => {
                        let mut i = i0 + (x - p.x) as u32 * st;
                        for _ in x..e {
                            out.px(lut[p.g.at(i) as usize]);
                            i += st;
                        }
                    }
                    None => out.run(lut[0], (e - x) as u16),
                },
                // HUF: the glyph's row y straight from its runs; a twin W
                // through the row buffer.
                Some(p) if p.twin == 0 => {
                    let gx = (x - p.x) as usize;
                    p.g.row_runs(&mut p.cur, (y - p.y) as u32, gx, gx + (e - x) as usize, |a, n| out.run(lut[a as usize], n));
                }
                Some(p) => {
                    if bi != gi {
                        p.g.row(&mut p.cur, (y - p.y) as u32, &mut buf);
                        bi = gi;
                    }
                    let gx = (x - p.x) as usize;
                    for (k, _) in (x..e).enumerate() {
                        out.px(lut[twin_buf(&buf, p.g.w, p.twin, gx + k) as usize]);
                    }
                }
                None => out.run(bg, (e - x) as u16),
            }
            x = e;
        }
    }
    #[cfg(test)]
    crate::probe::end();
}

/// Glyph `c` of `font` at half size, each pixel the mean coverage of a 2x2
/// block of the full-size glyph (same face, no extra font data). The glyph is
/// centred horizontally in `r`, which is painted entirely (`bg` outside the
/// glyph, so a redraw leaves nothing behind), and sits on `base` (exclusive
/// bottom y) exactly as the full-size glyph sits on its baseline: full-size
/// rows 2k, 2k + 1 below/above the baseline become half-size row k, so odd
/// glyph heights do not shift it. Used for the small +1 digit after the F78
/// readout.
pub fn label_half(font: Font, r: Rect, c: char, base: i16, fg: Color, bg: Color) {
    if r.w <= 0 || r.h <= 0 {
        return;
    }
    let Some((ya, yb)) = lcd::clip_rows(r.y.max(0), (r.y + r.h - 1).min(lcd::H as i16 - 1)) else {
        return;
    };
    let g = font.glyph(c as u32);
    // Full-size row of glyph row 0, relative to the baseline; left x of the
    // half-size glyph.
    let (top, ox) = match &g {
        Some(g) => (-(g.h as i32 + g.yoff as i32), r.x as i32 + ((r.w as i32 - (g.w as i32 + 1) / 2) >> 1)),
        None => (0, 0),
    };
    let x1 = (r.x + r.w - 1).min(lcd::W as i16 - 1);
    let (x0, y0, y1) = (r.x.max(0), ya, yb);
    let lut = ramp(fg, bg);
    #[cfg(test)]
    crate::probe::begin(crate::probe::TEXT, bg);
    lcd::set_window(x0 as u16, y0 as u16, x1 as u16, y1 as u16);
    let (x0, x1) = (x0 as i32, x1 as i32);
    let mut rows = [[0u8; MAXW]; 2];
    let mut cur = Cur::default();
    for y in y0..=y1 {
        let gy = 2 * (y as i32 - base as i32) - top;
        // Columns of this row inside the glyph (gx = 2 (x - ox) in 0..w):
        // ox ..= ox + (w - 1) / 2; background before and after.
        let (xa, xb) = match &g {
            Some(g) if g.w > 0 && gy > -2 && gy < g.h as i32 => (ox.max(x0), (ox + (g.w as i32 - 1) / 2).min(x1)),
            _ => (x1 + 1, x1),
        };
        for _ in x0..xa.min(x1 + 1) {
            lcd::data(bg);
        }
        if let Some(g) = &g {
            let (w, h) = (g.w as i32, g.h as i32);
            // Glyph rows gy, gy + 1 (zero outside the glyph).
            for (k, b) in rows.iter_mut().enumerate() {
                let py = gy + k as i32;
                if xa <= xb && py >= 0 && py < h {
                    g.row(&mut cur, py as u32, b);
                } else {
                    b.fill(0);
                }
            }
            for x in xa..=xb {
                let gx = 2 * (x - ox);
                let mut s = 0u32;
                for dx in 0..2 {
                    let px = gx + dx;
                    if px < w {
                        s += rows[0][px as usize] as u32 + rows[1][px as usize] as u32;
                    }
                }
                lcd::data(lut[((s + 2) / 4) as usize]);
            }
        }
        for _ in (xb + 1).max(xa).max(x0)..=x1 {
            lcd::data(bg);
        }
    }
    #[cfg(test)]
    crate::probe::end();
}

/// Fixed-cell label, redrawing only the cells whose character differs from
/// `prev` (same cell layout assumed; pass an empty `prev` for a full draw).
/// `grey` (colour, from, previous from): the cells from index `from` on
/// are drawn in that colour instead of `fg` (the DMM readout's digits below
/// the accuracy, ../docs/dmm-accuracy.md section 5); a cell whose colour
/// changed since `previous from` is redrawn.
pub fn cells_diff(font: Font, r: Rect, text: &str, prev: &str, widths: &[u8], fg: Color, bg: Color, grey: (Color, u8, u8)) {
    #[cfg(test)]
    crate::probe::group(true);
    let mut x = r.x;
    let mut it = text.chars();
    let mut ip = prev.chars();
    let full = prev.is_empty();
    let (gc, gs, pgs) = grey;
    for (i, &w) in widths.iter().enumerate() {
        let c = it.next().unwrap_or(' ');
        let pc = ip.next();
        let g = i as u8 >= gs;
        if full || pc != Some(c) || g != (i as u8 >= pgs) {
            let mut b = [0u8; 4];
            label(font, rect(x, r.y, w as i16, r.h), c.encode_utf8(&mut b), if g { gc } else { fg }, bg, 8, 0);
        }
        x += w as i16;
    }
    let end = r.x + r.w;
    if full && x < end {
        lcd::fill_rect(x as u16, r.y as u16, (end - x) as u16, r.h as u16, bg);
    }
    #[cfg(test)]
    crate::probe::group(false);
}

/// Rounded box (corners cut at `radius`, no anti-aliasing).
pub fn rbox(r: Rect, radius: i16, color: Color, outside: Color) {
    let x0 = r.x.max(0);
    let Some((ya, yb)) = lcd::clip_rows(r.y.max(0), r.y + r.h - 1) else {
        return;
    };
    #[cfg(test)]
    crate::probe::begin(crate::probe::SHAPE, outside);
    lcd::set_window(x0 as u16, ya as u16, (r.x + r.w - 1) as u16, yb as u16);
    let rr = radius as i32 * radius as i32;
    for y in ya - r.y..=yb - r.y {
        // Into the strip in a strip pass (lcd.rs), when the box is on the screen.
        let mut out = if r.x >= 0 && r.x + r.w <= lcd::W as i16 { lcd::row_out(r.y + y, r.x) } else { lcd::Out::panel() };
        let dy = if y < radius { radius - y } else if y >= r.h - radius { y - (r.h - radius - 1) } else { 0 };
        if radius >= 0 && r.w >= 2 * radius {
            // The row as three runs: `k` corner pixels outside on each side
            // (the same test as below, symmetric: dx = radius - k on both).
            let mut k = 0;
            while k < radius && (radius - k) as i32 * (radius - k) as i32 + dy as i32 * dy as i32 > rr {
                k += 1;
            }
            out.run(outside, k as u16);
            out.run(color, (r.w - 2 * k) as u16);
            out.run(outside, k as u16);
            continue;
        }
        for x in 0..r.w {
            let dx = if x < radius { radius - x } else if x >= r.w - radius { x - (r.w - radius - 1) } else { 0 };
            let dy = if y < radius { radius - y } else if y >= r.h - radius { y - (r.h - radius - 1) } else { 0 };
            let inside = (dx as i32 * dx as i32 + dy as i32 * dy as i32) <= radius as i32 * radius as i32;
            out.px(if inside { color } else { outside });
        }
    }
    #[cfg(test)]
    crate::probe::end();
}

/// Draw only the glyph boxes of `text` placed in `r` (pixels outside the
/// glyphs are left alone): for text over shapes such as rounded buttons.
pub fn glyphs(font: Font, r: Rect, text: &str, fg: Color, bg: Color, align: u8, spacing: i8) {
    if !lcd::rows_hit(r.y, r.y + r.h - 1) {
        return;
    }
    let mut pl: [Option<Placed>; MAXG] = [const { None }; MAXG];
    let n = layout(font, r, text, align, spacing, &mut pl);
    #[cfg(test)]
    crate::probe::begin(crate::probe::TEXT, bg);
    for (_i, p) in pl[..n].iter().enumerate() {
        let Some(p) = p else { continue };
        if p.g.w == 0 || p.g.h == 0 || p.x < 0 || p.y < 0 {
            continue;
        }
        // A strip pass (lcd.rs "strip rendering"): the strip's rows.
        let Some((ya, yb)) = lcd::clip_rows(p.y, p.y + p.g.h as i16 - 1) else {
            continue;
        };
        #[cfg(test)]
        crate::probe::sub(_i as u8);
        let x = p.x as u16;
        let lut = ramp(fg, bg);
        let w = p.g.w as u16 + p.twin as u16;
        lcd::set_window(x, ya as u16, x + w - 1, yb as u16);
        let mut buf = [0u8; MAXW];
        let mut cur = Cur::default();
        for gy in (ya - p.y) as u32..=(yb - p.y) as u32 {
            let mut out = if x + w <= lcd::W { lcd::row_out(p.y + gy as i16, x as i16) } else { lcd::Out::panel() };
            if p.twin == 0 {
                match p.g.col_walk(gy) {
                    None => p.g.row_runs(&mut cur, gy, 0, w as usize, |a, n| out.run(lut[a as usize], n)),
                    Some(Some((mut i, st))) => {
                        for _ in 0..w {
                            out.px(lut[p.g.at(i) as usize]);
                            i += st;
                        }
                    }
                    Some(None) => {
                        for _ in 0..w {
                            out.px(lut[0]);
                        }
                    }
                }
                continue;
            }
            p.g.row(&mut cur, gy, &mut buf);
            for gx in 0..w as usize {
                out.px(lut[twin_buf(&buf, p.g.w, p.twin, gx) as usize]);
            }
        }
    }
    #[cfg(test)]
    crate::probe::end();
}

/// Width in pixels of `text` as `label` lays it out (pen advance plus the
/// last glyph's width), e.g. to place a tag right before right-aligned text.
pub fn text_width(font: Font, text: &str, spacing: i8) -> i16 {
    let (mut pen, mut last) = (0i32, 0i32);
    let lh = font.line_h() as i32;
    for ch in text.chars() {
        let (adv, w) = match glyph_or_twin(font, ch) {
            // As `layout`: a space advances at least lh / 3.
            Some((g, _)) if ch == ' ' => ((g.adv as i32).max(lh / 3), g.w as i32),
            Some((g, tw)) => (g.adv as i32 + tw as i32, g.w as i32 + tw as i32),
            None => (font.line_h() as i32, font.line_h() as i32),
        };
        last = pen + w;
        pen += adv + spacing as i32;
    }
    last as i16
}

/// Map our unit text to the stock font's code points (no 'k' / 'µ' glyphs:
/// the stock writes "K" and "u", e.g. "KΩ"). The energy units keep 'k'
/// ("kWh", "kVAh": our LETTERS k, stockfont_w.rs; F14 / TEXT22 have one).
pub fn unit_text<'a>(u: &str, buf: &'a mut [u8; 16]) -> &'a str {
    let mut n = 0;
    let energy = u.ends_with("Wh") || u.ends_with("VAh");
    // '\u{b0}' in u, as bytes: a str search for a non-ASCII char pulls
    // core's two-way string searcher (~1 KB) into region B.
    let deg = u.as_bytes().windows(2).any(|w| w == [0xC2, 0xB0]);
    for c in u.chars() {
        let c = match c {
            'k' if energy => 'k',
            'k' => 'K',
            '\u{b5}' => 'u',
            '\u{b0}' => continue,
            'C' if deg => '\u{2103}',
            'F' if deg => '\u{2109}',
            c => c,
        };
        let mut t = [0u8; 4];
        let s = c.encode_utf8(&mut t);
        if n + s.len() > buf.len() {
            break;
        }
        buf[n..n + s.len()].copy_from_slice(s.as_bytes());
        n += s.len();
    }
    core::str::from_utf8(&buf[..n]).unwrap_or("")
}

