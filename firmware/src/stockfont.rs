/// Stock alignment 0..8: 0 left/top, 1 left/vcenter, 2 left/bottom, 3 right/top,
/// 4 right/vcenter, 5 right/bottom, 6 hcenter/top, 7 hcenter/bottom, 8 center.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct Rect {
    pub x: i16,
    pub y: i16,
    pub w: i16,
    pub h: i16,
}

pub const fn rect(x: i16, y: i16, w: i16, h: i16) -> Rect {
    Rect { x, y, w, h }
}

const MAXG: usize = 48;

struct Placed {
    g: Glyph,
    x: i16,
    y: i16,
    /// Synthesised glyph (`glyph_or_twin`): the bitmap drawn a second time
    /// `twin` px to the right (max coverage of the two); 0 = plain.
    twin: i16,
    /// Row cursor (HUF glyphs decode their rows in order).
    cur: Cur,
}

/// Every character of `s` has a glyph in `font` (W, k: ours where missing).
pub fn has_all(font: Font, s: &str) -> bool {
    s.chars().all(|c| glyph_or_twin(font, c).is_some())
}

