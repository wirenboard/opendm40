#!/usr/bin/env python3
"""Generate src/stockfont_usb.rs: the USB symbol (the trident, upright), the
"USB host" icon (the stock firmware has none), in two sizes:
  * glyph 0x22 of the status-bar icon font SAVE_BT (0x0805B2E8, 0x21 =
    Bluetooth, 16 x 20 4 bpp): 14 x 20, 4 bpp (ui.rs status_right);
  * glyph 0x30 of the scope battery font SC_BATT (0x0806BD44, 1 bpp, 16 px
    line): 11 x 18, 1 bpp (scope_ui.rs usb_icon, the scope top bar).

The large one is drawn at 8x with PIL (stem with an arrow head, a round foot,
a branch with a circle on the left and one with a square on the right) and
area-averaged to 4 bpp alpha (RAW4, column-major, high nibble first); the
small one is pixel art (SMALL below), 1 bpp (BIT1, column-major, MSB first).

    /usr/bin/python3 tools/mkusbglyph.py      (from firmware/; needs PIL)
"""
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'stockfont_usb.rs')
K = 8


def draw(W, H, stroke=2.0):
    """The trident designed on a 14 x 20 grid, scaled to W x H."""
    im = Image.new('L', (14 * K, 20 * K), 0)
    d = ImageDraw.Draw(im)
    s = round(stroke * K * 14 / W)  # the stroke, in output px
    cx = 14 * K // 2
    # Arrow head on top, stem down to the foot.
    d.polygon([(cx, 0), (cx - 3 * K, 4 * K), (cx + 3 * K, 4 * K)], fill=255)
    d.rectangle((cx - s / 2, 3.5 * K, cx + s / 2, 17 * K), fill=255)
    # Round foot.
    r = 2.1 * K
    d.ellipse((cx - r, 20 * K - 2 * r, cx + r, 20 * K), fill=255)
    # Left branch: from the stem down-left, then up, a circle on top.
    lx = 1.8 * K
    d.line([(cx, 15 * K), (lx, 12 * K)], fill=255, width=s)
    d.rectangle((lx - s / 2, 9.5 * K, lx + s / 2, 12.4 * K), fill=255)
    rc = 1.8 * K
    d.ellipse((lx - rc, 10 * K - 2 * rc, lx + rc, 10 * K), fill=255)
    # Right branch: higher, a square on top.
    rx = 14 * K - 1.8 * K
    d.line([(cx, 12 * K), (rx, 9 * K)], fill=255, width=s)
    d.rectangle((rx - s / 2, 7.5 * K, rx + s / 2, 9.4 * K), fill=255)
    q = 1.6 * K
    d.rectangle((rx - q, 7.6 * K - 2 * q, rx + q, 7.6 * K), fill=255)
    r = im.resize((W, H), Image.BOX)
    return [[min(15, (r.getpixel((x, y)) + 8) // 17) for x in range(W)] for y in range(H)]


# The small one by hand (an area-averaged one comes out lopsided): 11 x 18,
# the top bar's height but a row at each end (y 1..18 of 0..19: top on the
# battery's and the badges' top row; y 20 is the graph frame / meter strip);
# the battery outline's 1 px weight; odd width so the stem (column 5), the
# arrow head and the foot centre on one column. Square higher on the right,
# circle lower on the left, as the large one. yoff -2: the font's line is 16
# px, the glyph hangs 2 rows below it (scope_ui.rs USB_ICON).
SMALL = [
    '.....@.....',
    '....@@@....',
    '...@@@@@...',
    '..@@@@@@@..',
    '.....@.....',
    '.....@..@@@',
    '.....@..@@@',
    '.@...@..@@@',
    '@@@..@...@.',
    '.@...@...@.',
    '.@...@...@.',
    '.@...@..@..',
    '..@..@.@...',
    '...@.@@....',
    '....@@.....',
    '....@@@....',
    '...@@@@@...',
    '....@@@....',
]


# The Bluetooth rune for the same bar (the stock scope fonts have none; the
# status bars' SAVE_BT 0x21 is 16 x 20): 7 x 13, the same 1 px weight, 45
# degree strokes crossing on the stem (column 3). yoff 1: top on bar row 3,
# vertically centred on the USB symbol's rows (scope_ui.rs usb_icon).
BT = [
    '...@...',
    '...@@..',
    '...@.@.',
    '@..@..@',
    '.@.@.@.',
    '..@@@..',
    '...@...',
    '..@@@..',
    '.@.@.@.',
    '@..@..@',
    '...@.@.',
    '...@@..',
    '...@...',
]


def entry(lines, name, font, code, px, four, yoff=0):
    W, H = len(px[0]), len(px)
    if four:
        nib = [px[y][x] for x in range(W) for y in range(H)] + [0]
        b = bytes(nib[i] << 4 | nib[i + 1] for i in range(0, W * H, 2))
    else:
        bits = [px[y][x] >= 8 for x in range(W) for y in range(H)]
        b = bytes(sum(0x80 >> k for k, v in enumerate(bits[i:i + 8]) if v) for i in range(0, len(bits), 8))
    lines.append('    // %s' % name)
    for row in px:
        lines.append('    //   ' + ''.join(('.:-=+*#%@@'[min(9, v * 10 // 16)] if four else ('@' if v >= 8 else '.')) for v in row))
    lines.append("    (0x%08X, '\\u{%x}', %s, %d, %d, %d, %d, b\"%s\")," % (font, code, 'true' if four else 'false', W, H, W, yoff, ''.join('\\x%02x' % c for c in b)))


def main():
    lines = ['// @generated by tools/mkusbglyph.py - do not edit by hand.',
             '// The USB symbol and the scope bar\'s Bluetooth rune (stockfont.rs glyph_or_twin):',
             '// (font object address, char, 4 bpp, w, h, adv, yoff, column-major bitmap).', '',
             'pub static USB_GLYPHS: [(u32, char, bool, u8, u8, u8, i8, &[u8]); 3] = [']
    entry(lines, 'SAVE_BT 0x22, status bar', 0x0805B2E8, 0x22, draw(14, 20), True)
    entry(lines, 'SC_BATT 0x30, scope top bar', 0x0806BD44, 0x30, [[15 if c == '@' else 0 for c in r] for r in SMALL], False, -2)
    entry(lines, 'SC_BATT 0x31, scope top bar Bluetooth', 0x0806BD44, 0x31, [[15 if c == '@' else 0 for c in r] for r in BT], False, 1)
    lines.append('];')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('src/stockfont_usb.rs written')


if __name__ == '__main__':
    sys.exit(main())
